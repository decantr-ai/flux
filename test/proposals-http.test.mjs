import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { createStore } from '../src/store.mjs';
import { startServer } from '../src/server.mjs';

test('proposal endpoint is protected, source-bound, revision checked and never dispatches', async t => {
  const dir = mkdtempSync(join(tmpdir(), 'flux-proposals-http-'));
  const store = createStore(dir); let calls = 0, fingerprint = 'initial';
  store.setProject({ id: 'p', sessionId: 's', sessions: [{ id: 's' }], items: [], decisions: [] });
  store.append({ id: 'origin', kind: 'decision_recorded', projectId: 'p', sessionId: 's', actor: 'Codex', data: { decision: { id: 'idea', title: 'An optional followup', status: 'proposed' } } });
  const app = await startServer({ store, watch: false, runtimeFingerprint: async () => fingerprint, queueCommand: async () => calls++ });
  t.after(async () => { await app.close(); rmSync(dir, { recursive: true, force: true }); });
  const state = await (await fetch(`${app.address}/api/state`)).json();
  assert.equal(state.runtime.modelVersion, 10);
  assert.deepEqual(state.proposalActions, { available: true });
  const input = { proposalId: 'idea', proposalKind: 'decision', choice: 'later', expectedRevision: state.contextRevision };
  const post = (payload, headers = {}) => fetch(`${app.address}/api/proposals`, { method: 'POST', headers: { 'Content-Type': 'application/json', 'X-Flux-CSRF': state.csrfToken, ...headers }, body: JSON.stringify(payload) });
  assert.equal((await post(input, { 'X-Flux-CSRF': '' })).status, 403);
  assert.equal((await post(input, { Origin: 'https://foreign.invalid' })).status, 403);
  assert.equal((await post(input, { 'Content-Type': 'text/plain' })).status, 415);
  assert.equal((await post({ ...input, proposalSourceId: 'client-forgery' })).status, 400);
  let response = await post(input);
  assert.equal(response.status, 200);
  const result = await response.json();
  assert.equal(result.proposal.disposition, 'later');
  assert.equal(result.event.source.ref, 'origin');
  assert.equal((await post({ ...input, choice: 'dismiss' })).status, 409);
  const current = store.snapshot();
  response = await post({ ...input, choice: 'plan', expectedRevision: current.contextRevision });
  assert.equal(response.status, 200);
  const planned = await response.json();
  assert.equal(planned.item.status, 'pending');
  assert.equal((await post({ ...input, choice: 'plan' })).status, 200);
  assert.equal(store.snapshot().project.items.length, 1);
  assert.equal(calls, 0);
  fingerprint = 'updated';
  assert.equal((await post({ ...input, choice: 'plan' })).status, 409);
});
